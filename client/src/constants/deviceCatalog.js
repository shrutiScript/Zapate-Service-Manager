export const getCompanyId = (companyName) => {
  if (!companyName) return '';
  const norm = String(companyName).trim().toLowerCase();
  const match = DEVICE_BRANDS.find(
    (b) => b.id === norm || b.name.toLowerCase() === norm || norm.includes(b.id) || b.id.includes(norm)
  );
  return match ? match.id : 'other';
};

export const getModelsForCompany = (companyIdOrName) => {
  if (!companyIdOrName) return [];
  const targetId = getCompanyId(companyIdOrName);
  return DEVICE_MODELS.filter((m) => m.companyId === targetId);
};
